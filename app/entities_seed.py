# Seeded entries whose first version matched too much: (watchlist slug, old name, old aliases, new name). Applied once at
# start to an entry you have not edited (same name AND same aliases as the old seed); the new aliases come from the list above.
SEED_FIXES = [("ransomware-groups", "Conti", ["Conti ransomware"], "Conti (ransomware)")]


def fix_seeded(db) -> list[int]:
    """Returns the ids of the entities that were corrected (they need re-indexing)."""
    import json

    changed = []
    wanted = {name: aliases for _slug, _title, _desc, items in BUILTIN_WATCHLISTS for name, aliases in items}
    for slug, old_name, old_aliases, new_name in SEED_FIXES:
        row = db.execute("SELECT e.id, e.aliases FROM entities e JOIN watchlists w ON w.id = e.watchlist_id WHERE w.slug = ? AND e.name = ?",
                         (slug, old_name)).fetchone()
        if row is None or json.loads(row["aliases"] or "[]") != old_aliases or new_name not in wanted:
            continue
        db.execute("UPDATE entities SET name = ?, aliases = ? WHERE id = ?", (new_name, json.dumps(wanted[new_name]), row["id"]))
        changed.append(int(row["id"]))
    return changed
